package tui

import "github.com/kibomibo/sshmon/internal/collect"

// errText — текст ошибки для показа на экране. Ошибки транспорта несут в себе
// куски ответа удалённой стороны (баннер сервера, сообщение sshd, вывод команды),
// поэтому доверия к ним не больше, чем к строке лога: escape-последовательность
// в тексте ошибки доедет до терминала оператора тем же путём.
//
// Данные (строки логов, процессы, порты, контейнеры, имена юнитов) чистятся
// раньше — на входе в collect, см. collect.SanitizeLine. Здесь остались только
// error-значения: они не проходят через разбор и добираются до экрана как есть.
func errText(err error) string {
	if err == nil {
		return ""
	}
	return collect.SanitizeLine(err.Error())
}
